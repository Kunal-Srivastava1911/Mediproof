"""Render eval `Report` metrics to the markdown tables `make eval` writes into the README."""

from __future__ import annotations

import statistics
from pathlib import Path

from evals.harness import Report, coverage_accuracy_curve
from schemas.ground_truth import HELD_OUT_FAULTS

_START = "<!-- BENCHMARK:START -->"
_END = "<!-- BENCHMARK:END -->"


def _pct(c: int, t: int) -> str:
    return f"{100 * c / t:.1f}%" if t else "—"


def render_markdown(report: Report) -> str:
    lines: list[str] = []
    lines.append(f"_Auto-generated by `make eval` over {report.n_claims} synthetic claims "
                 f"({report.n_clean} clean, {report.n_faulty} with a seeded fault). "
                 f"Fully reproducible from seeds._\n")

    # classification
    cc, ct = report.classification_correct, report.classification_total
    lines.append("**Document classification** (P0 keyword baseline)\n")
    lines.append(f"- accuracy: **{_pct(cc, ct)}** ({cc}/{ct} documents)\n")

    # extraction
    lines.append("**Field extraction** (deterministic layer, vs ground truth)\n")
    lines.append("| Document type | Exact match | Normalized match |")
    lines.append("|---|---|---|")
    tot_e = [0, 0]
    tot_n = [0, 0]
    for t in sorted(report.exact_by_type):
        ec, et = report.exact_by_type[t]
        nc, nt = report.norm_by_type[t]
        tot_e[0] += ec
        tot_e[1] += et
        tot_n[0] += nc
        tot_n[1] += nt
        lines.append(f"| {t} | {_pct(ec, et)} | {_pct(nc, nt)} |")
    lines.append(f"| **all** | **{_pct(*tot_e)}** | **{_pct(*tot_n)}** |\n")

    # audit: open-world split, rules only vs rules + verified agents
    agents_ran = report.agent_claims > 0
    lines.append("**Audit engine** (recall per fault family, vs injected ground truth; "
                 "★ = held-out family, no rule written for it)\n")
    lines.append("| Fault family | Rules only | Rules + agents |")
    lines.append("|---|---|---|")
    held = {f.value for f in HELD_OUT_FAULTS}
    groups = {"seen": [0, 0, 0], "held-out": [0, 0, 0]}  # caught_rules, caught_all, total
    for fault in sorted(report.fault_recall, key=lambda f: (f in held, f)):
        c, t = report.fault_recall[fault]
        rc, _ = report.fault_recall_rules.get(fault, [0, t])
        g = groups["held-out" if fault in held else "seen"]
        g[0] += rc
        g[1] += c
        g[2] += t
        both = f"{_pct(c, t)} ({c}/{t})" if agents_ran else "not run"
        lines.append(f"| {fault}{' ★' if fault in held else ''} | {_pct(rc, t)} ({rc}/{t}) "
                     f"| {both} |")
    for name, (rc, c, t) in groups.items():
        if t:
            both = f"**{_pct(c, t)}**" if agents_ran else "not run"
            lines.append(f"| **all {name}** | **{_pct(rc, t)}** | {both} |")
    lines.append("")
    n = report.n_clean or 1
    lines.append(f"- **Severe review items shown on clean files:** "
                 f"{report.clean_false_positives / n:.2f} per clean claim "
                 f"({report.clean_fp_rules} from rules, {report.clean_fp_agents} from agents, "
                 f"across {report.n_clean} clean claims).")
    if agents_ran:
        lines.append(f"- **Clean claims showing ≥ 1 agent item:** {report.clean_with_agent_item}"
                     f"/{report.n_clean}; agent items held back by the verifier: "
                     f"{report.held_back}.")
        lines.append(f"- **Agent auditor model:** `{report.agent_model}` — the agent column "
                     f"measures this model, not any other.")
        lines.append(f"- **Agent auditor cost:** {report.llm_calls} LLM calls, "
                     f"${report.llm_cost_usd:.2f} live spend this run "
                     f"(replayed and free-tier calls cost $0).\n")
    else:
        lines.append(f"- **Agent auditor: not run in this eval.** "
                     f"{report.agent_note or ''} The rules-only column is the baseline the "
                     f"agents are measured against; held-out families are 0% for rules by "
                     f"design.\n")

    # coverage-accuracy
    curve = coverage_accuracy_curve(report.coverage_points)
    if curve:
        lines.append("**Coverage–accuracy** (route the lowest-confidence fields to review)\n")
        lines.append("| Sent to review | Auto-accepted | Accuracy of auto-accepted |")
        lines.append("|---|---|---|")
        for reviewed, kept, acc in curve:
            lines.append(f"| {reviewed*100:.0f}% | {kept*100:.0f}% | {acc*100:.1f}% |")
        lines.append("")

    # hybrid unit economics
    sc = report.source_counts
    total_fields = sum(sc.values()) or 1
    rule = sc.get("rule", 0) + sc.get("fusion", 0)
    llm = sc.get("llm", 0)
    med = statistics.median(report.latencies) if report.latencies else 0.0
    lines.append("**Hybrid unit economics**\n")
    lines.append(f"- deterministic layer fills **{100*rule/total_fields:.1f}%** of extracted "
                 f"fields; **{llm} LLM calls** were needed across the whole set "
                 f"(the LLM only touches low-confidence fields).")
    lines.append(f"- median end-to-end latency: **{med*1000:.0f} ms/claim** "
                 f"(digital path, no OCR).\n")
    return "\n".join(lines)


def write_results(report: Report, path: str | Path) -> Path:
    path = Path(path)
    path.write_text("# MediProof benchmark results\n\n" + render_markdown(report),
                    encoding="utf-8")
    return path


def update_readme(report: Report, readme_path: str | Path) -> bool:
    """Replace the README block between the BENCHMARK markers. Returns True if it updated."""
    readme_path = Path(readme_path)
    text = readme_path.read_text(encoding="utf-8")
    block = f"{_START}\n\n{render_markdown(report)}\n\n{_END}"
    if _START in text and _END in text:
        pre = text[: text.index(_START)]
        post = text[text.index(_END) + len(_END):]
        readme_path.write_text(pre + block + post, encoding="utf-8")
        return True
    return False
